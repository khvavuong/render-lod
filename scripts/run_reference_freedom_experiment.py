"""Isolated, bounded ablation of reference-led design freedom; never edits production jobs.

Four incremental treatments, independent repetitions, one provider/model/resolution/brief.
Image blocks are composed explicitly to prevent production adapter constraints leaking in.
The free arm is a quality-ceiling control, NOT a geometry-valid deliverable.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import mimetypes
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from typing import Any

import httpx

from v365_archviz.artifacts import atomic_write
from v365_archviz.config import Settings
from v365_archviz.providers.gemini import DEFAULT_ENDPOINT, _find_output_image

ARMS = ("R0_reference_free", "R1_source_envelope", "R2_registered_camera", "R3_locked_programme")
VERSION = "reference-freedom-1"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path: Path, value: object) -> None:
    atomic_write(path, json.dumps(value, ensure_ascii=False, indent=2).encode() + b"\n")


def source_contract(scene: dict, design: dict) -> dict:
    focus = [
        item for item in scene["elements"] if item["semantic_role"] in {"main_shed", "office_block"}
    ]
    if not focus:
        raise ValueError("source has no classified focus buildings; no guessed envelope allowed")
    minimum = [min(item["bounding_box"]["minimum"][axis] for item in focus) for axis in range(3)]
    boxes = [
        {
            "source_element_id": item["scene_element_id"],
            "role": item["semantic_role"],
            "minimum_m": [
                round(item["bounding_box"]["minimum"][axis] - minimum[axis], 3) for axis in range(3)
            ],
            "maximum_m": [
                round(item["bounding_box"]["maximum"][axis] - minimum[axis], 3) for axis in range(3)
            ],
        }
        for item in focus
    ]
    facades = [
        facade
        for building in design["buildings"]
        if building.get("treatment", "focus") == "focus"
        for facade in building["facades"]
    ]
    return {
        "source_focus_elements": boxes,
        "geometry_note": "Axis-aligned source envelopes, "
        "not an exact mesh or approved roof design.",
        "unapproved_pipeline_programme": {
            "office_entrances": sum(f.get("office_entrance") is not None for f in facades),
            "loading_doors": sum(len(f["loading_docks"]) for f in facades),
            "roof_assemblies": len(design.get("roof_assemblies", [])),
            "provenance": "Generated by Design DNA; NOT automatically source/client requirements.",
        },
    }


def build_sample(config: dict, arm: str, view: str, contract: dict, model: str) -> dict:
    if arm not in ARMS:
        raise ValueError(f"unknown treatment: {arm}")
    specification = config["views"][view]
    prompt = config["brief"] + "\n\nPHOTOGRAPHIC PURPOSE\n" + specification["intent"]
    images = [dict(reference) for reference in config["references"]]
    if arm != ARMS[0]:
        prompt += (
            "\n\nMEASURED SOURCE ENVELOPE\n"
            "Retain the relative positions, footprints and height envelopes of the focus source "
            "volumes below. Develop facade architecture inside these envelopes. Source elements "
            "may be parts of one continuous shed; do not invent an extra building at each seam. "
            "No facade kit, office count, dock count, colour zoning or motif is prescribed. "
            "New architectural details are proposals, not source facts.\n"
            + json.dumps(contract["source_focus_elements"], ensure_ascii=False)
        )
    if arm in ARMS[2:]:
        images.insert(
            0,
            {
                "path": specification["base"],
                "role": "registered_camera_and_envelope",
                "instruction": "This is a camera-registered envelope / programme render, NOT the "
                "finished architecture. Retain its camera, projected building placement, measured "
                "massing and roof silhouette. Its low-poly planting, plain surfaces, colours, "
                "facade "
                "grammar and generated openings are not architectural requirements. Replace them "
                "with a reference-led coherent design. Do not copy the reference image's camera.",
            },
        )
        prompt += (
            "\n\nREGISTERED CAMERA\nRetain the camera and building positions shown in the "
            "registered render. Do not switch to another angle, add a horizon absent from the "
            "render, change perspective or relocate office architecture onto an unrelated face."
        )
    if arm == ARMS[3]:
        images[0]["instruction"] = images[0]["instruction"].replace(
            "and generated openings are not architectural requirements",
            "are not architectural requirements; generated functional openings ARE binding here",
        )
        programme = contract["unapproved_pipeline_programme"]
        prompt += (
            "\n\nEXPERIMENTAL PROGRAMME LOCK\nThis treatment intentionally makes the pipeline's "
            "unapproved programme binding: preserve all functional entrances, loading doors and "
            "continuous roof assemblies in the registered render, including their positions and "
            "count. No adding, removing or relocating a door, dock or entrance. Develop how they "
            "are framed, shaded and detailed; the total project counts are not a demand to "
            "show invisible/rear openings in this shot.\n" + json.dumps(programme)
        )
    return {
        "version": VERSION,
        "arm": arm,
        "view": view,
        "prompt": prompt,
        "images": images,
        "model": model,
        "image_size": config["image_size"],
        "aspect_ratio": config["aspect_ratio"],
        "store": False,
        "camera_metadata_sha256": digest(Path(specification["camera"])),
        "reference_hashes": {item["path"]: digest(Path(item["path"])) for item in images},
    }


def signature(sample: dict) -> str:
    return hashlib.sha256(
        json.dumps(sample, sort_keys=True, ensure_ascii=False).encode()
    ).hexdigest()


def generate_one(sample: dict, directory: Path, api_key: str) -> dict:
    # Persist in-flight BEFORE the paid request; ambiguous/failed calls are not auto-retried.
    record = {"status": "in_flight", "request_signature": signature(sample), "sample": sample}
    write_json(directory / "manifest.json", record)
    blocks: list[dict[str, str]] = [{"type": "text", "text": sample["prompt"]}]
    for item in sample["images"]:
        blocks.extend(
            [
                {"type": "text", "text": f"{item['role']}: {item['instruction']}"},
                {
                    "type": "image",
                    "mime_type": mimetypes.guess_type(item["path"])[0] or "image/png",
                    "data": base64.b64encode(Path(item["path"]).read_bytes()).decode(),
                },
            ]
        )
    payload: dict[str, Any] = {
        "model": sample["model"],
        "input": blocks,
        "store": False,
        "response_format": {
            "type": "image",
            "aspect_ratio": sample["aspect_ratio"],
            "image_size": sample["image_size"],
        },
    }
    try:
        with httpx.Client(timeout=httpx.Timeout(240, connect=15)) as client:
            response = client.post(
                DEFAULT_ENDPOINT, json=payload, headers={"x-goog-api-key": api_key}
            )
            response.raise_for_status()
            document = response.json()
        output = _find_output_image(document)
        if output is None:
            raise ValueError("provider returned no image")
        content, media_type = output
        extension = ".png" if media_type == "image/png" else ".jpg"
        path = directory / ("generated" + extension)
        atomic_write(path, content)
        record.update(
            status="complete",
            output=str(path),
            output_sha256=digest(path),
            provider_request_id=document.get("id"),
            media_type=media_type,
        )
    except (httpx.HTTPError, ValueError) as exc:
        record.update(
            status="failed",
            error_type=type(exc).__name__,
            http_status=exc.response.status_code
            if isinstance(exc, httpx.HTTPStatusError)
            else None,
        )
    write_json(directory / "manifest.json", record)
    return record


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config", type=Path)
    parser.add_argument("--execute", action="store_true", help="explicitly enable paid image calls")
    parser.add_argument("--workers", type=int, choices=(1, 2), default=2)
    arguments = parser.parse_args()
    config = json.loads(arguments.config.read_text(encoding="utf-8"))
    settings = Settings.from_env()
    scene = json.loads(Path(config["scene"]).read_text(encoding="utf-8"))
    design = json.loads(Path(config["design"]).read_text(encoding="utf-8"))
    contract = source_contract(scene, design)
    root = Path(config["output_root"])
    repetitions = config["repetitions"]
    count = len(ARMS) * len(config["views"]) * repetitions
    if (
        not isinstance(repetitions, int)
        or repetitions < 1
        or count > config["max_generation_calls"]
    ):
        raise ValueError("invalid repetitions or experiment exceeds paid-call cap")
    samples = []
    for arm in ARMS:
        for view in config["views"]:
            for repetition in range(1, repetitions + 1):
                sample = build_sample(config, arm, view, contract, settings.gemini_image_model)
                sample["repetition"] = repetition
                samples.append((sample, root / arm / view / f"rep-{repetition}"))
    plan = {
        "experiment_id": config["experiment_id"],
        "version": VERSION,
        "config_sha256": digest(arguments.config),
        "source_sha256": digest(Path(config["scene"])),
        "design_sha256": digest(Path(config["design"])),
        "contract": contract,
        "independent_calls": count,
        "model": settings.gemini_image_model,
        "note": "Exploratory, one source site, two roles, n=3. No seeds or consistency guarantees.",
        "samples": [
            {"directory": str(directory), "request_signature": signature(sample)}
            for sample, directory in samples
        ],
    }
    plan_path = root / "experiment_plan.json"
    if plan_path.is_file() and json.loads(plan_path.read_text(encoding="utf-8")) != plan:
        raise ValueError("existing experiment has different inputs; choose a new output_root")
    write_json(plan_path, plan)
    pending = []
    complete = []
    for sample, directory in samples:
        manifest = directory / "manifest.json"
        if manifest.is_file():
            cached = json.loads(manifest.read_text(encoding="utf-8"))
            if cached["request_signature"] != signature(sample):
                raise ValueError("cached sample does not match this request")
            if cached["status"] != "complete":
                raise ValueError(f"ambiguous/failed paid call: {directory}; no automatic retry")
            if digest(Path(cached["output"])) != cached["output_sha256"]:
                raise ValueError(f"cached output changed: {directory}")
            complete.append(cached)
        else:
            write_json(directory / "request.json", sample)
            pending.append((sample, directory))
    print(
        f"plan: {count} images; complete={len(complete)} pending={len(pending)}; "
        f"model={settings.gemini_image_model}",
        flush=True,
    )
    if not arguments.execute:
        return 0
    if not settings.gemini_api_key:
        raise ValueError("Gemini key is not configured")
    with ThreadPoolExecutor(max_workers=arguments.workers) as executor:
        futures = {
            executor.submit(generate_one, sample, directory, settings.gemini_api_key): sample
            for sample, directory in pending
        }
        for future in as_completed(futures):
            record = future.result()
            complete.append(record)
            item = record["sample"]
            print(
                f"{item['arm']} / {item['view']} / {item['repetition']}: {record['status']}",
                flush=True,
            )
            write_json(
                root / "run_summary.json",
                {
                    "planned": count,
                    "complete": sum(row["status"] == "complete" for row in complete),
                    "failed": sum(row["status"] != "complete" for row in complete),
                },
            )
    return 0 if all(row["status"] == "complete" for row in complete) else 2


if __name__ == "__main__":
    raise SystemExit(main())
